// ---------------------------------------------------------------- tooltip (W_Tooltip) — read-only in hover, editable when focused
function tooltipHTML(key, editable) {
  const g = S.gear[key], it = g && ITEM[g.id];
  if (!it) return `<div class="tt empty"><p class="hint">${esc(D.slotLabel[SLOT[key]?.kind] || '')}</p></div>`;
  const tal = it.k === 'talisman';
  const rar = tal ? null : RAR[g.rar];
  const fx = gearEffects(g);
  const nSlots = effectSlots(g);
  const stats = [];
  if (it.cd != null) stats.push(`<span><img src="${D.art.timer}" alt="">${+it.cd.toFixed(2)}s</span>`);
  if (it.soul) stats.push(`<span><img src="${D.art.soul}" alt="">${it.soul}</span>`);
  const effRow = (tpl, src, i) => {
    const t = D.templates[tpl], e = D.effects[t.e];
    const ed = editable && src === 'rolled';
    return `<div class="eff${ed ? ' edit' : ''}" ${ed ? `data-act="pickfx" data-i="${i}"` : ''}>
      <span class="effic"><img class="fr" src="${D.art.effectFrame}" alt="">${e.i ? `<img src="${e.i}" alt="">` : flagMark('effect')}</span>
      <div><h5>${esc(tplName(tpl))}</h5><p>${tplDesc(tpl)}</p></div></div>`;
  };
  const rolled = (g.fx || []).slice(0, nSlots);
  let effects = (it.fx || []).map(t => effRow(t, 'unique')).join('');
  if (tal) effects = fx.map(f => effRow(f.tpl, 'talisman')).join('');
  else for (let i = 0; i < nSlots; i++) {
    effects += rolled[i] ? effRow(rolled[i], 'rolled', i)
      : editable ? `<button class="eff add" data-act="pickfx" data-i="${i}"><span class="effic"><img class="fr" src="${D.art.effectFrame}" alt=""><img class="plusic" src="${D.art.plus}" alt=""></span><div><h5>+</h5></div></button>` : '';
  }
  const enId = it.ue || g.en;
  const en = enId && D.enchantments[enId];
  const enchHTML = en ? `<div class="ench${editable && !it.ue ? ' edit' : ''}" ${editable && !it.ue ? 'data-act="pickench"' : ''}>
      <span class="effic"><img src="${en.i}" alt=""></span>
      <div><h5>${esc(en.n)}${it.ue ? '' : ' ' + TIER_NUM[(g.enl || 1) - 1]}</h5><p>${enchDesc(enId)}</p>${it.ue ? '' : flagMark('enchantment', 'level')}</div></div>`
    : editable && !tal ? `<button class="ench add" data-act="pickench"><span class="effic"><img src="${D.art.enchSwirl}" alt=""></span><div><h5>${esc(UI.Label_Enchantment || 'Enchantment')}</h5></div></button>` : '';
  const rarBadge = rar ? `<span class="rtag" style="--rc:${rar.c}"><i style="-webkit-mask-image:url('${rar.badge}');mask-image:url('${rar.badge}')"></i>${esc(rar.n.toUpperCase())}</span>` : '';
  const paired = it.uq || it.base;  // base weapon <-> its unique: one entry, rarity decides which
  const rarPick = editable && !tal && (!it.u || paired) ? `<div class="rpick">${D.rarities.filter(r => paired || r.id !== 'Unique').map(r =>
    `<button data-act="rar" data-r="${r.id}" style="--rc:${r.c}" ${r.id === g.rar ? 'aria-pressed="true"' : ''}>${esc(r.n)}</button>`).join('')}</div>` : '';
  const ipCtl = tal ? `<div class="talvl">${it.lv.map((l, i) => `<button data-act="tlv" data-l="${i + 1}" ${(g.lv || 1) === i + 1 ? 'aria-pressed="true"' : ''}>${TIER_NUM[i] || i + 1}</button>`).join('')}</div>`
    : editable ? `<span class="ipv"><span class="ipicon sm"></span><button data-act="ip" data-d="-1">‹</button><input id="ipin" type="number" inputmode="numeric" min="1" max="999" value="${g.ip}"><button data-act="ip" data-d="1">›</button></span>`
    : `<span class="ipv"><span class="ipicon sm"></span>${g.ip}</span>`;
  const storm = !tal && editable ? `<button class="storm" data-act="storm" ${g.storm ? 'aria-pressed="true"' : ''} title="Soul storm reward">✦</button>` : (g.storm ? '<span class="storm on">✦</span>' : '');
  return `<div class="tt" style="--rc:${rar ? rar.c : '#C7CAD3'}">
    ${editable ? '' : `<div class="ribbon">${esc(UI.tag_equipped || 'Equipped')}</div>`}
    <div class="upper">
      <div class="meta"><div class="line1">${storm}${ipCtl}${rarBadge}</div>
        <h4>${esc(it.n)}</h4>
        ${stats.length ? `<div class="srow">${stats.join('')}</div>` : ''}
        ${rarPick}</div>
      <div class="bigic" data-k="${esc(it.id)}" style="--rc:${rar ? rar.c : '#5a6372'}"><span class="rbg"></span>${(tal ? it.lv[(g.lv || 1) - 1]?.i : it.i) ? `<img src="${tal ? it.lv[(g.lv || 1) - 1].i : it.i}" alt="">` : flagMark('item')}</div>
    </div>
    <div class="lower">
      ${it.d ? `<p class="desc">${esc(it.d)}</p>` : ''}
      ${enchHTML}${effects}
      ${statsHTML(it).replace('<details class="wstats">', `<details class="wstats"${statsOpen ? ' open' : ''}>`)}
      ${editable ? `<div class="acts"><button class="btn" data-act="change">Change</button><button class="btn ghost" data-act="remove">Remove</button></div>` : ''}
    </div></div>`;
}
