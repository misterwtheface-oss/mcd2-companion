// rarity across a base / unique pair: Unique = the unique item, anything lower = its base item (UniqueSubstitution)
function setRarity(g, r) {
  const it = ITEM[g.id];
  const to = r === 'Unique' ? (it.uq || g.id) : (it.base || g.id);
  g.rar = r;
  if (to !== g.id) {
    g.id = to;
    swapped = to;
  }
  const nit = ITEM[g.id];
  const pool = new Set(D.pools[nit.p].map(([t]) => t));
  const fixed = new Set((nit.fx || []).map(t => D.templates[t].e));
  const seen = new Set();
  g.fx = (g.fx || []).map(t => {  // keep a rolled effect only if the new item and rarity can still roll it
    const tp = t && D.templates[t];
    if (!tp || !pool.has(t) || (tp.ra && !tp.ra.includes(r)) || fixed.has(tp.e) || seen.has(tp.e)) return null;
    seen.add(tp.e);
    return t;
  });
}
let swapped = null;
function equip(id) {
  const it = ITEM[id];
  const rar = it.k === 'talisman' ? null : it.u ? 'Unique' : (S.gear[focus]?.rar && S.gear[focus].rar !== 'Unique' ? S.gear[focus].rar : 'Rare');
  S.gear[focus] = it.k === 'talisman' ? { id, lv: 1 } : { id, rar, ip: defaultIP(rar), fx: [] };
  save(); closeOv(); renderAll();
  if (!isDesktop()) openSheet();
}
document.addEventListener('click', ev => {
  const fl = ev.target.closest('.flag');
  if (fl) { ev.stopPropagation(); toast(fl.dataset.flag); return; }
  const slot = ev.target.closest('[data-slot]');
  if (slot) {
    const key = slot.dataset.slot;
    setFocus(key);
    if (!S.gear[key]) push(() => picker(key));
    else if (!isDesktop()) openSheet();
    return;
  }
  const a = ev.target.closest('[data-act]');
  if (!a) { if (ev.target.id === 'ov') closeOv(); return; }
  const d = a.dataset, g = S.gear[focus];
  switch (d.act) {
    case 'close': closeOv(); break;
    case 'back': back(); break;
    case 'lvl': S.level = Math.max(1, Math.min(D.rules.levelMax, S.level + +d.d)); save(); renderStats(); break;
    case 'totals': ovStack = []; push(totals); break;
    case 'totf': totFilter = d.f; totals(); break;
    case 'flags': ovStack = []; push(flagsView); break;
    case 'skin': ovStack = []; push(skinPicker); break;
    case 'setskin': S.skin = d.id; save(); closeOv(); renderChar(); break;
    case 'equip': equip(d.id); break;
    case 'change': push(() => picker(focus)); break;
    case 'remove': delete S.gear[focus]; save(); closeOv(); renderAll(); break;
    case 'rar': setRarity(g, d.r); save(); renderAll(); break;
    case 'ip': g.ip = Math.max(1, Math.min(999, g.ip + +d.d)); save(); renderAll(); break;
    case 'storm': g.storm = !g.storm; save(); renderAll(); break;
    case 'tlv': g.lv = +d.l; save(); renderAll(); break;
    case 'pickfx': push(() => fxPicker(+d.i)); break;
    case 'setfx': (g.fx ||= [])[+d.i] = d.t || null; save(); back(); renderAll(); break;
    case 'pickench': push(enchPicker); break;
    case 'setench': if (d.id) { g.en = d.id; g.enl = +d.l; } else { delete g.en; delete g.enl; } save(); back(); renderAll(); break;
  }
});
