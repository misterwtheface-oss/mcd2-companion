let totFilter = 'all';
function totals() {
  const sum = {};
  for (const s of SLOTS) {
    const g = S.gear[s.key];
    if (!g || !ITEM[g.id]) continue;
    if (totFilter !== 'enchantments') for (const { tpl } of gearEffects(g)) {
      const t = D.templates[tpl];
      (sum['e:' + t.e] ||= { kind: 'e', id: t.e, v: 0, n: 0 }).v += tplValue(t) || 0;
      sum['e:' + t.e].n++;
    }
    const en = ITEM[g.id].ue || g.en;
    if (en && totFilter !== 'effects') (sum['n:' + en] ||= { kind: 'n', id: en, v: 0, n: 0, l: [] }).l.push(ITEM[g.id].ue ? '' : TIER_NUM[(g.enl || 1) - 1]);
  }
  const cats = [['Offensive', UI.effect_offensive], ['Defensive', UI.effect_defensive], ['Utility', UI.effect_utility]];
  const row = x => {
    if (x.kind === 'e') {
      const e = D.effects[x.id];
      return `<div class="eff"><span class="effic"><img class="fr" src="${D.art.effectFrame}" alt="">${e.i ? `<img src="${e.i}" alt="">` : ''}</span>
        <div><h5>${esc(e.n)}<span class="tot">${fmtNum(x.v, e.f)}</span></h5><p>${fill(e.d, fmtNum(x.v, e.f))}</p></div></div>`;
    }
    const e = D.enchantments[x.id];
    return `<div class="ench"><span class="effic"><img src="${e.i}" alt=""></span><div><h5>${esc(e.n)} <span class="tot">${x.l.filter(Boolean).join(' · ')}</span></h5><p>${enchDesc(x.id)}</p></div></div>`;
  };
  const groups = cats.map(([c, label]) => {
    const xs = Object.values(sum).filter(x => ((x.kind === 'e' ? D.effects[x.id].c : D.enchantments[x.id].c) || 'Utility') === c);
    return xs.length ? `<h4 class="grp">${esc(label)}</h4>${xs.map(row).join('')}` : '';
  }).join('');
  const tabs = [['all', UI.inventory_totaleffects_all, D.art.cat.all], ['effects', UI.inventory_totaleffects_effects, D.art.cat.effects],
    ['enchantments', UI.inventory_totaleffects_enchantments, D.art.cat.enchantment]]
    .map(([k, n, i]) => `<button data-act="totf" data-f="${k}" ${totFilter === k ? 'aria-pressed="true"' : ''}><img src="${i}" alt="">${esc(n || k)}</button>`).join('');
  overlay(UI.inventory_totaleffects_toggle, `<div class="tabs">${tabs}</div>${flagMark('stats', 'sum')}${groups || '<p class="hint">–</p>'}`, { keepScroll: true, cls: 'totals' });
}
