function slotHTML(key, g, extra = '') {
  const s = SLOT[key], it = g && ITEM[g.id];
  if (!it) {
    return `<button class="slot empty" data-slot="${key}" ${extra} aria-label="${esc(D.slotLabel[s.kind] || s.kind)}">
      <img class="sil" src="${D.art.empty[s.kind]}" alt=""><img class="plus" src="${D.art.plus}" alt=""></button>`;
  }
  return cellHTML(it, g, `data-slot="${key}" ${extra}`);
}
function cellHTML(it, g, attrs) {
  const rar = it.k === 'talisman' ? null : (g?.rar || (it.u ? 'Unique' : 'Common'));
  const icon = it.k === 'talisman' ? (it.lv[(g?.lv || 1) - 1]?.i || it.i) : it.i;
  const ench = g && (g.en || it.ue);
  return `<button class="slot${rar ? ' r-' + rar : ''}" ${attrs} style="--rc:${rar ? RAR[rar].c : '#5a6372'}" aria-label="${esc(it.n)}">
    <span class="rbg"></span>${icon ? `<img class="ic" src="${icon}" alt="">` : `<span class="noart">${esc(it.n)}</span>${flagMark('item')}`}
    ${ench ? `<img class="b-ench" src="${D.art.enchSwirl}" alt="">` : ''}
    ${g && it.k !== 'talisman' && g.ip ? `<span class="b-ip">${g.ip}</span>` : ''}
    ${g && it.k === 'talisman' ? `<span class="b-lv">${TIER_NUM[(g.lv || 1) - 1] || g.lv}</span>` : ''}</button>`;
}
