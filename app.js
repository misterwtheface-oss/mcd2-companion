function load() {
  try {
    const h = location.hash.slice(1);
    if (h.startsWith('b=')) return clean(Object.assign({}, DEFAULT, JSON.parse(decodeURIComponent(atob(h.slice(2))))));
    const ls = localStorage.getItem('mcd2.build');
    if (ls) return clean(Object.assign({}, DEFAULT, JSON.parse(ls)));
  } catch (e) { /* fall through */ }
  return structuredClone(DEFAULT);
}
function clean(s) {  // a build saved by an older data build: drop what the current data no longer has
  s.gear = s.gear && typeof s.gear === 'object' ? s.gear : {};
  for (const [key, g] of Object.entries(s.gear)) {
    const it = g && SLOT[key] && ITEM[g.id];
    if (!it) { delete s.gear[key]; continue; }
    if (it.k === 'talisman') continue;
    if (!RAR[g.rar]) g.rar = it.u ? 'Unique' : it.k === 'artifact' ? 'Special' : 'Rare';  // newGear's defaults (S is not set yet)
    if (!(+g.ip >= 1)) g.ip = Math.max(1, Math.floor((s.level || 50) * D.rules.ipPerLevel) + (RAR[g.rar]?.ipo || 0));
    g.fx = Array.isArray(g.fx) ? g.fx.map(t => (t && D.templates[t] ? t : null)) : [];
    if (g.en && !D.enchantments[g.en]) { delete g.en; delete g.enl; }
  }
  return s;
}
// Menu levels are history entries that keep the URL they were pushed on, so closing a menu lands on an entry
// carrying an older #b=. Hashes this page wrote are its own history, not a shared link: they must not reload S.
let curHash = location.hash;
const ownHashes = new Set(['', curHash]);
function save() {
  const j = JSON.stringify(S);
  localStorage.setItem('mcd2.build', j);
  curHash = '#b=' + btoa(encodeURIComponent(j));
  ownHashes.add(curHash);
  history.replaceState(history.state, '', curHash);  // keep the menu entry's state
}

// ---------------------------------------------------------------- numbers + text (game NumberToTextFormattingData)
function fmtNum(v, f) {
  if (v == null) return '?';
  if (!f) return String(+(+v).toFixed(2));
  let x = v * f.mul + f.off;
  if (f.pct) x *= 100;
  const p = 10 ** f.maxf;
  x = Math.sign(x) * Math.round(Math.abs(x) * p) / p;  // HalfFromZero
  let s = x.toFixed(f.maxf);
  if (s.includes('.')) {  // keep between MinFractionalDigits and MaxFractionalDigits
    const [a, b] = s.split('.');
    const frac = b.replace(/0+$/, '').padEnd(f.minf, '0');
    s = frac ? `${a}.${frac}` : a;
  }
  return (f.sign && x > 0 ? '+' : '') + s + (f.pct ? '%' : '');
}
// {0} = the given value, {1..n} = the entry's extra placeholders (p: [[value | null, format]])
const fill = (text, val, extra) => stLinks(esc(text || '').replace(/\{(\d+)\}/g, (m, i) => {
  if (+i === 0) return `<b>${esc(val)}</b>`;
  const x = extra?.[i - 1];
  return `<b>${x ? esc(fmtNum(x[0], x[1])) : '?'}</b>`;
}));
// status names in description text (game name, or the tag before "status": "the Strength status") -> tap / hover card.
// Artifact buffs are left out: their names are the artifacts' own names.
const ST_TERMS = Object.entries(D.statuses).filter(([, s]) => !s.a).flatMap(([k, s]) => [[s.n, k], ...(k !== s.n && !k.includes('_') ? [[k + '(?= status)', k]] : [])]);
const ST_OF = Object.fromEntries(Object.entries(D.statuses).filter(([, s]) => !s.a).map(([k, s]) => [s.n, k]));
const ST_RE = new RegExp(String.raw`\b(?:${ST_TERMS.map(([t]) => t).sort((a, b) => b.length - a.length).join('|')})\b`, 'g');
const stTag = (k, text) => `<span class="stt" data-act="status" data-s="${k}">${text}</span>`;
function stLinks(html) { return html.replace(ST_RE, m => stTag(ST_OF[m] || m, m)); }
const tplValue = t => t.v ?? (t.r ? t.r[1] : null);
function tplName(id) {
  const t = D.templates[id], e = D.effects[t.e];
  return e.n + (t.t && t.t !== 'U' ? ' ' + t.t : '');
}
function tplDesc(id) {
  const t = D.templates[id], e = D.effects[t.e];
  return fill(e.d, fmtNum(tplValue(t), e.f), e.p);
}
function enchDesc(id, lvl = 1) {  // tv = per-level values (I / II / III) when the number is the level's magnitude
  const e = D.enchantments[id];
  if (!e.d.includes('{0}')) return stLinks(esc(e.d));
  const v = e.tv ? e.tv[Math.min(lvl, e.tv.length) - 1] : e.v;
  return fill(e.d, v == null ? '?' : fmtNum(v, e.f), e.p);
}

// ---------------------------------------------------------------- derived values
const defaultIP = r => Math.max(1, Math.floor(S.level * D.rules.ipPerLevel) + (RAR[r]?.ipo || 0));
function effectSlots(g) {
  const it = ITEM[g.id];
  if (!it || it.k === 'talisman') return 0;
  const base = RAR[g.rar]?.fx || 0;
  return Math.min(D.rules.maxEffects - (it.fx?.length || 0) - (it.ue ? 1 : 0), base + (g.storm ? 1 : 0));  // a built-in enchantment holds an effect slot
}
function gearEffects(g) {  // [{tpl, src}] every effect an equipped item carries
  const it = ITEM[g.id];
  if (!it) return [];
  if (it.k === 'talisman') return (it.lv[(g.lv || 1) - 1]?.fx || []).map(t => ({ tpl: t, src: 'talisman' }));
  return [...(it.fx || []).map(t => ({ tpl: t, src: 'unique' })),
          ...(g.fx || []).slice(0, effectSlots(g)).filter(Boolean).map(t => ({ tpl: t, src: 'rolled' }))];
}
function itemPowers() {
  const cat = { melee: [], ranged: [], armor: [], artifact: [] };
  for (const s of SLOTS) {
    const g = S.gear[s.key];
    if (!g || !ITEM[g.id] || s.kind === 'talisman') continue;
    const c = ['helmet', 'chest', 'legs', 'boots'].includes(s.kind) ? 'armor' : s.kind;
    cat[c].push(g.ip);
  }
  const avg = a => a.length ? Math.round(a.reduce((x, y) => x + y, 0) / a.length) : null;
  const all = Object.values(cat).flat();
  return { total: avg(all), melee: avg(cat.melee), ranged: avg(cat.ranged), armor: avg(cat.armor), artifact: avg(cat.artifact) };
}

// ---------------------------------------------------------------- flags (things the game files do not give us)
const FLAG = Object.groupBy ? Object.groupBy(D.flags, f => f.area) : D.flags.reduce((m, f) => ((m[f.area] ||= []).push(f), m), {});
// origin tag on built-in effects / enchantments. Unique: no gear rolls it, it exists only on the items listed (orange =
// one item). Enchantment: a unique's built-in enchantment, held in an effect slot (the item still takes a book).
// Basic: a rollable effect; native when this item's own type rolls it, else named by the types that do.
const GEAR_GRP = k => k === 'melee' || k === 'ranged' ? 'weapon' : k === 'artifact' || k === 'talisman' ? k : 'armor';
const GRP_N = { weapon: 'Weapon', armor: 'Armor', artifact: 'Artifact' };
const ROLL_GRP = {};  // effect id -> gear groups whose pools hold it
for (const it of D.items) if (it.p != null) (D.pools[it.p] || []).forEach(([t]) => (ROLL_GRP[D.templates[t].e] ||= new Set()).add(GEAR_GRP(it.k)));
function originTag(it, kind, id) {  // -> { c, n, tip }; it = the item carrying it (null in search: only Unique shows)
  if (kind === 'c') return { c: 'uq', n: 'Unique', tip: `Only on ${it.n}` };  // a companion talisman's summon
  const x = kind === 'n' ? D.enchantments[id] : D.effects[id];
  const onlyOn = x.only?.length ? `Only on ${x.only.map(i => ITEM[i]?.n || i).join(', ')}` : '';
  const uq = onlyOn && { c: 'uq' + (x.only.length > 1 ? ' few' : ''), n: 'Unique', tip: onlyOn };
  if (kind === 'n') return it ? { c: 'oench' + (onlyOn ? ' uq' : ''), n: 'Enchantment', tip: onlyOn || 'Built-in enchantment in an effect slot' } : uq || null;
  if (uq || !it) return uq || null;
  const grps = Object.keys(GRP_N).filter(g => ROLL_GRP[id]?.has(g));
  if (grps.includes(GEAR_GRP(it.k))) return { c: 'basic', n: 'Basic', tip: `Also rolls on ${GRP_N[GEAR_GRP(it.k)].toLowerCase()}` };
  const n = grps.map(g => GRP_N[g]).join(' · ');
  return { c: 'cross', n: `${n} effect`, tip: `Rolls on ${n.toLowerCase().replace(' · ', ' and ')}, not on ${it.k === 'talisman' ? 'talismans' : GRP_N[GEAR_GRP(it.k)].toLowerCase()}` };
}
function originMark(it, kind, id, inButton = false) {  // inside a button (picker tile) the tag is plain text
  const t = originTag(it, kind, id);
  if (!t) return '';
  return inButton ? `<i class="otag ${t.c}">${esc(t.n)}</i>` : `<button class="otag ${t.c}" data-flag="${esc(t.tip)}">${esc(t.n)}</button>`;
}
function flagMark(area, match) {
  if (!FEATURES.flags) return '';
  const f = (FLAG[area] || []).find(x => !match || x.what.includes(match));
  return f ? `<button class="flag" data-flag="${esc(f.what)}" aria-label="Data note">⚑</button>` : '';
}

