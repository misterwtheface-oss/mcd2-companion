// rarity across a base / unique pair: Unique = the unique item, anything lower = its base item (UniqueSubstitution)
function setRarity(g, r) {
  const it = ITEM[g.id];
  const to = r === 'Unique' ? (it.uq || g.id) : (it.base || g.id);
  g.rar = r;
  if (to !== g.id) {
    g.id = to;
    swapped = to;
  }
  const nit = ITEM[g.id];
  const pool = new Set(D.pools[nit.p].map(([t]) => t));
  const fixed = new Set((nit.fx || []).map(t => D.templates[t].e));
  const seen = new Set();
  g.fx = (g.fx || []).map(t => {  // keep a rolled effect only if the new item and rarity can still roll it
    const tp = t && D.templates[t];
    if (!tp || !pool.has(t) || (tp.ra && !tp.ra.includes(r)) || fixed.has(tp.e) || seen.has(tp.e)) return null;
    seen.add(tp.e);
    return t;
  });
}
let swapped = null;
function newGear(id, prev) {  // a fresh item at the builder's defaults (prev = rarity to keep from the replaced item)
  const it = ITEM[id];
  const rar = it.k === 'talisman' ? null : it.u ? 'Unique' : it.k === 'artifact' ? 'Special'
    : (prev && prev !== 'Unique' ? prev : 'Rare');
  return it.k === 'talisman' ? { id, lv: Math.min(3, it.lv.length) } : { id, rar, ip: defaultIP(rar), fx: [], storm: true };  // soul storm slot on by default
}
